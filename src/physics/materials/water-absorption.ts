export type WaterSource = "Pope & Fry 1997" | "Segelstein 1981";

// One sorted node list: Segelstein below 380 nm, Pope & Fry, Segelstein above 727.5 nm.
const POPE_END_NM = POPE_START_NM + POPE_STEP_NM * (POPE.length - 1);
const NM: number[] = [];
const ALPHA: number[] = [];
for (let i = 0; i < SEGELSTEIN.length; i += 2) {
  if (SEGELSTEIN[i] < POPE_START_NM) {
    NM.push(SEGELSTEIN[i]);
    ALPHA.push(SEGELSTEIN[i + 1]);
  }
}
POPE.forEach((a, i) => {
  NM.push(POPE_START_NM + i * POPE_STEP_NM);
  ALPHA.push(a);
});
for (let i = 0; i < SEGELSTEIN.length; i += 2) {
  if (SEGELSTEIN[i] > POPE_END_NM) {
    NM.push(SEGELSTEIN[i]);
    ALPHA.push(SEGELSTEIN[i + 1]);
  }
}

/** First Segelstein node above the Pope & Fry range (729 nm). */
const SEG_RESUME_NM = NM[NM.indexOf(POPE_END_NM) + 1];

/** Table range in m. */
export const WATER_LAMBDA_MIN = NM[0] * 1e-9;
export const WATER_LAMBDA_MAX = NM[NM.length - 1] * 1e-9;

/** Which table covers wavelength λ (m), by the node at or below λ; null outside 200–2500 nm. */
export function waterSource(lambda: number): WaterSource | null {
  const nm = lambda * 1e9;
  if (!(nm >= NM[0] && nm <= NM[NM.length - 1])) return null;
  return nm >= POPE_START_NM && nm < SEG_RESUME_NM ? "Pope & Fry 1997" : "Segelstein 1981";
}

/** Absorption coefficient α of pure water at wavelength λ (m), 1/m; NaN outside 200–2500 nm. */
export function waterAbsorption(lambda: number): number {
  const nm = lambda * 1e9;
  if (!(nm >= NM[0] && nm <= NM[NM.length - 1])) return NaN;
  let lo = 0;
  let hi = NM.length - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (NM[mid] <= nm) lo = mid;
    else hi = mid;
  }
  const f = (nm - NM[lo]) / (NM[hi] - NM[lo]);
  return 100 * Math.exp(Math.log(ALPHA[lo]) + f * (Math.log(ALPHA[hi]) - Math.log(ALPHA[lo])));
}
